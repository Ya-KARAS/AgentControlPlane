export function normalizeLocalReviewLanguage(value) {
  return value === "en" ? "en" : "zh-CN";
}

export function localReviewText(language, key, values = {}) {
  const selected = MESSAGES[normalizeLocalReviewLanguage(language)];
  const fallback = MESSAGES["zh-CN"];
  const template = selected[key] ?? fallback[key] ?? key;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : `{${name}}`,
  );
}

export function localReviewMessageKeys(language) {
  return Object.keys(MESSAGES[normalizeLocalReviewLanguage(language)]).sort();
}
