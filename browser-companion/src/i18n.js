export function makeT(language) {
  const table = STRINGS[language] ?? STRINGS.zh;
  return (key, params = {}) => {
    let text = table[key] ?? STRINGS.en[key] ?? key;
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
    return text;
  };
}
